//! Recording data model — the `manifest.json` schema (spec §4.4).
//!
//! The manifest is the **sole source of truth** for a recording (spec §11): no
//! SQLite index, no separate metadata DB. `storage list` scans
//! `~/.bubbaloop/recordings/*/manifest.json`. These structs are the typed view
//! of that file; [`crate::storage::manifest`] handles load/save/validation.
//!
//! Forward compatibility: every struct that maps to a JSON object captures
//! unknown fields in an `extra` map (`#[serde(flatten)]`) so a manifest written
//! by a newer recorder round-trips through an older binary without data loss
//! (spec §15, schema-version drift risk).

use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;

/// Current manifest schema version written by this build.
pub const MANIFEST_SCHEMA_VERSION: u32 = 1;

/// A recording's `manifest.json` — the source of truth for one recording.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct Recording {
    /// Manifest schema version. Loaders preserve unknown fields across versions.
    pub schema_version: u32,
    /// Recording name (caller-assigned; never generated by the recorder, §3.3.2).
    pub name: String,
    /// Machine that hosted the recorder for this recording.
    pub machine_id: String,
    /// Zenoh router endpoint the recorder was a client of, for provenance.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub fleet_router: Option<String>,
    /// Recorder-clock timestamp of session start (nanoseconds since epoch).
    pub started_at_ns: u64,
    /// Recorder-clock timestamp of `stop`. `None` while recording or if the
    /// session was interrupted by a crash (manifest stays "open", §3.3.9).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub ended_at_ns: Option<u64>,
    /// Wall-clock duration once finalized.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub duration_ns: Option<u64>,
    /// Total bytes across all finalized chunks.
    #[serde(default)]
    pub size_bytes: u64,
    /// Capture mode.
    pub mode: RecordingMode,
    /// Sliding-window length for ring-buffer mode (§3.3.5).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub window_secs: Option<u64>,
    /// Ring-buffer trigger policy (`manual` in v1).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub trigger: Option<Trigger>,
    /// The resolved topic selection used for this recording.
    pub selection: Selection,
    /// One entry per recorded topic/channel.
    #[serde(default)]
    pub channels: Vec<Channel>,
    /// Finalized chunks in index order. Per-chunk `uploaded_at_ns` is the only
    /// upload-status signal — the recording is fully uploaded iff every chunk has it.
    #[serde(default)]
    pub chunks: Vec<Chunk>,
    /// Profile this recording was started from, for provenance only (§3.3.2).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub profile_name: Option<String>,
    /// Canonical hash of the profile (§4.3.3), durable across cosmetic edits.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub profile_sha256: Option<String>,
    /// Version string of the recorder that produced this manifest.
    #[serde(default)]
    pub recorder_version: String,
    /// Free-form tags (Phase 3 search; carried through verbatim in v1).
    #[serde(default)]
    pub tags: Vec<String>,
    /// Unknown fields from newer schema versions, preserved on round-trip.
    #[serde(flatten)]
    pub extra: BTreeMap<String, serde_json::Value>,
}

/// Capture mode (`mode` in the manifest). Distinct from the command-envelope
/// `SessionMode`, which carries the window inline; the manifest keeps `mode` and
/// `window_secs` as separate fields per §4.4.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RecordingMode {
    /// Continuous capture until `stop`.
    #[default]
    Streaming,
    /// Sliding in-memory window, sealed on `flush` (§3.3.5).
    RingBuffer,
}

/// Ring-buffer trigger policy. Only `Manual` is accepted in v1; `OnEvent` is
/// Phase 3 (spec §4.3.1) but is representable so newer manifests round-trip.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum Trigger {
    /// User calls `record flush` to seal the window.
    Manual,
    /// External event seals the window (Phase 3).
    OnEvent,
}

/// The resolved topic selection (§4.4 `selection`). Patterns compose additively:
/// `(topics ∪ regex_match) - exclude` (spec §11).
#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq, Eq)]
pub struct Selection {
    /// Literal/wildcard include patterns.
    #[serde(default)]
    pub topics: Vec<String>,
    /// Additive regex include.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub regex: Option<String>,
    /// Subtractive exclude patterns removed from the union.
    #[serde(default)]
    pub exclude: Vec<String>,
    /// Whether `bubbaloop/local/**` (SHM-only) topics were included.
    #[serde(default)]
    pub include_local: bool,
}

/// One recorded channel (§4.4 `channels`). Preserves the original Zenoh encoding
/// so replay can be byte-identical (§4.5).
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct Channel {
    /// Full Zenoh topic key.
    pub topic: String,
    /// MCAP channel id assigned at start.
    pub channel_id: u16,
    /// Messages captured on this channel.
    #[serde(default)]
    pub message_count: u64,
    /// MCAP `message_encoding` (`cbor` / `protobuf` / `raw`).
    pub message_encoding: String,
    /// Original Zenoh sample encoding (e.g. `application/cbor`).
    pub zenoh_encoding: String,
    /// Fully-qualified protobuf schema name, when known.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub schema_name: Option<String>,
    /// First/last publish-time bounds on this channel.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub publish_time_first_ns: Option<u64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub publish_time_last_ns: Option<u64>,
    /// Unknown fields preserved on round-trip.
    #[serde(flatten)]
    pub extra: BTreeMap<String, serde_json::Value>,
}

/// One finalized chunk (§4.4 `chunks`, §3.3.6).
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct Chunk {
    /// Filename `chunk-{index:06}-{sha256_prefix8}.mcap`.
    pub name: String,
    /// Zero-based chunk index.
    pub index: u32,
    /// On-disk size in bytes.
    pub size_bytes: u64,
    /// Full 64-char lowercase hex SHA-256 of the finalized chunk.
    pub sha256: String,
    /// Recorder-clock bounds of messages in this chunk.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub log_time_first_ns: Option<u64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub log_time_last_ns: Option<u64>,
    /// When this chunk was confirmed in the remote backend. `None` = not yet
    /// uploaded; this is the only per-chunk upload-status signal (§4.4).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub uploaded_at_ns: Option<u64>,
    /// Remote ETag from the successful PUT, for cross-checking.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub remote_etag: Option<String>,
    /// Unknown fields preserved on round-trip.
    #[serde(flatten)]
    pub extra: BTreeMap<String, serde_json::Value>,
}

impl Chunk {
    /// The canonical filename for a chunk given its index and hex digest,
    /// per §3.3.6: `chunk-{index:06}-{prefix8}.mcap`.
    pub fn canonical_name(index: u32, sha256_hex: &str) -> String {
        let prefix = &sha256_hex[..sha256_hex.len().min(8)];
        format!("chunk-{index:06}-{prefix}.mcap")
    }

    /// Whether this chunk's recorded `name` matches the canonical form derived
    /// from its `index` and `sha256`. A mismatch means the manifest is internally
    /// inconsistent (e.g. hand-edited).
    pub fn name_is_canonical(&self) -> bool {
        self.name == Self::canonical_name(self.index, &self.sha256)
    }

    /// Whether this chunk has been confirmed uploaded.
    pub fn is_uploaded(&self) -> bool {
        self.uploaded_at_ns.is_some()
    }
}

/// Derived lifecycle state of a recording (§4.4). `Recording` vs `Interrupted`
/// cannot be told from the manifest alone — it depends on whether the recorder
/// currently has a live session of the same name — so callers pass that in.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lifecycle {
    /// Live session, manifest still open.
    Recording,
    /// Normal stop — `ended_at_ns` set.
    Complete,
    /// Manifest open but no live session (crash, §3.3.9).
    Interrupted,
}

impl Recording {
    /// Construct a fresh, open (not-yet-ended) recording manifest.
    pub fn new(name: impl Into<String>, machine_id: impl Into<String>, started_at_ns: u64) -> Self {
        Self {
            schema_version: MANIFEST_SCHEMA_VERSION,
            name: name.into(),
            machine_id: machine_id.into(),
            fleet_router: None,
            started_at_ns,
            ended_at_ns: None,
            duration_ns: None,
            size_bytes: 0,
            mode: RecordingMode::Streaming,
            window_secs: None,
            trigger: None,
            selection: Selection::default(),
            channels: Vec::new(),
            chunks: Vec::new(),
            profile_name: None,
            profile_sha256: None,
            recorder_version: String::new(),
            tags: Vec::new(),
            extra: BTreeMap::new(),
        }
    }

    /// Number of chunks confirmed uploaded.
    pub fn uploaded_chunk_count(&self) -> usize {
        self.chunks.iter().filter(|c| c.is_uploaded()).count()
    }

    /// True when every chunk has been uploaded (and there is at least one chunk).
    pub fn is_fully_uploaded(&self) -> bool {
        !self.chunks.is_empty() && self.chunks.iter().all(Chunk::is_uploaded)
    }

    /// Whether the manifest is "open" (no `ended_at_ns`).
    pub fn is_open(&self) -> bool {
        self.ended_at_ns.is_none()
    }

    /// Derive lifecycle state. `session_active` = the recorder currently reports
    /// a live session with this recording's name (§4.4).
    pub fn lifecycle(&self, session_active: bool) -> Lifecycle {
        match (self.ended_at_ns, session_active) {
            (Some(_), _) => Lifecycle::Complete,
            (None, true) => Lifecycle::Recording,
            (None, false) => Lifecycle::Interrupted,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample_manifest_json() -> &'static str {
        r#"{
            "schema_version": 1,
            "name": "outdoor_test_3",
            "machine_id": "jetson_alpha",
            "fleet_router": "zenoh://10.0.0.1:7447",
            "started_at_ns": 1748275200000000000,
            "ended_at_ns": 1748275300000000000,
            "duration_ns": 100000000000,
            "size_bytes": 4567890123,
            "mode": "streaming",
            "window_secs": null,
            "trigger": null,
            "selection": {
                "topics": ["bubbaloop/global/*/cam_*/compressed"],
                "regex": null,
                "exclude": ["**/health"],
                "include_local": false
            },
            "channels": [{
                "topic": "bubbaloop/global/jetson_alpha/cam_front/compressed",
                "channel_id": 0,
                "message_count": 12345,
                "message_encoding": "cbor",
                "zenoh_encoding": "application/cbor",
                "schema_name": "bubbaloop.camera.v1.CompressedImage",
                "publish_time_first_ns": 1748275200123000000,
                "publish_time_last_ns": 1748275299987000000
            }],
            "chunks": [{
                "name": "chunk-000000-a1b2c3d4.mcap",
                "index": 0,
                "size_bytes": 786432,
                "sha256": "a1b2c3d4e5f6a7b8c9d0e1f2a3b4c5d6e7f8a9b0c1d2e3f4a5b6c7d8e9f0a1b2",
                "log_time_first_ns": 1748275200000000000,
                "log_time_last_ns": 1748275260000000000,
                "uploaded_at_ns": 1748275305000000000,
                "remote_etag": "\"a1b2c3d4e5f6\""
            }],
            "profile_name": "demo",
            "profile_sha256": "abc123def456",
            "recorder_version": "0.1.0",
            "tags": []
        }"#
    }

    #[test]
    fn parses_spec_example_manifest() {
        let r: Recording = serde_json::from_str(sample_manifest_json()).unwrap();
        assert_eq!(r.name, "outdoor_test_3");
        assert_eq!(r.mode, RecordingMode::Streaming);
        assert_eq!(r.channels.len(), 1);
        assert_eq!(r.chunks.len(), 1);
        assert_eq!(r.chunks[0].sha256.len(), 64);
        assert!(r.is_fully_uploaded());
        assert!(!r.is_open());
        assert_eq!(r.lifecycle(false), Lifecycle::Complete);
    }

    #[test]
    fn roundtrip_is_stable() {
        let r: Recording = serde_json::from_str(sample_manifest_json()).unwrap();
        let json = serde_json::to_string(&r).unwrap();
        let r2: Recording = serde_json::from_str(&json).unwrap();
        assert_eq!(r, r2);
    }

    #[test]
    fn preserves_unknown_fields_across_versions() {
        // A manifest from a hypothetical schema_version 2 with new fields.
        let future = r#"{
            "schema_version": 2,
            "name": "future_rec",
            "machine_id": "jetson_beta",
            "started_at_ns": 1,
            "mode": "ring_buffer",
            "window_secs": 60,
            "trigger": "manual",
            "selection": {"topics": ["a"], "exclude": [], "include_local": false},
            "retention_policy": {"tier": "cold", "days": 30},
            "encryption": "aes-256-gcm"
        }"#;
        let r: Recording = serde_json::from_str(future).unwrap();
        assert_eq!(r.mode, RecordingMode::RingBuffer);
        assert_eq!(r.window_secs, Some(60));
        assert_eq!(r.trigger, Some(Trigger::Manual));
        // Unknown top-level fields are retained verbatim.
        assert!(r.extra.contains_key("retention_policy"));
        assert_eq!(
            r.extra.get("encryption").unwrap(),
            &serde_json::Value::String("aes-256-gcm".into())
        );

        // ...and survive a round-trip so an old writer doesn't drop them.
        let json = serde_json::to_string(&r).unwrap();
        assert!(json.contains("retention_policy"));
        assert!(json.contains("aes-256-gcm"));
    }

    #[test]
    fn upload_status_derives_from_chunks() {
        let mut r = Recording::new("r", "m", 0);
        assert!(!r.is_fully_uploaded()); // no chunks yet
        r.chunks.push(Chunk {
            name: "chunk-000000-aaaaaaaa.mcap".into(),
            index: 0,
            size_bytes: 10,
            sha256: "aa".repeat(32),
            log_time_first_ns: None,
            log_time_last_ns: None,
            uploaded_at_ns: Some(5),
            remote_etag: None,
            extra: Default::default(),
        });
        r.chunks.push(Chunk {
            name: "chunk-000001-bbbbbbbb.mcap".into(),
            index: 1,
            size_bytes: 10,
            sha256: "bb".repeat(32),
            log_time_first_ns: None,
            log_time_last_ns: None,
            uploaded_at_ns: None,
            remote_etag: None,
            extra: Default::default(),
        });
        assert_eq!(r.uploaded_chunk_count(), 1);
        assert!(!r.is_fully_uploaded());
        r.chunks[1].uploaded_at_ns = Some(7);
        assert!(r.is_fully_uploaded());
    }

    #[test]
    fn open_manifest_lifecycle_depends_on_session() {
        let r = Recording::new("live", "m", 1);
        assert!(r.is_open());
        assert_eq!(r.lifecycle(true), Lifecycle::Recording);
        assert_eq!(r.lifecycle(false), Lifecycle::Interrupted);
    }

    #[test]
    fn canonical_chunk_name() {
        let hex = "a1b2c3d4e5f6a7b8c9d0e1f2a3b4c5d6e7f8a9b0c1d2e3f4a5b6c7d8e9f0a1b2";
        assert_eq!(Chunk::canonical_name(0, hex), "chunk-000000-a1b2c3d4.mcap");
        assert_eq!(Chunk::canonical_name(42, hex), "chunk-000042-a1b2c3d4.mcap");

        let c = Chunk {
            name: "chunk-000000-a1b2c3d4.mcap".into(),
            index: 0,
            size_bytes: 1,
            sha256: hex.into(),
            log_time_first_ns: None,
            log_time_last_ns: None,
            uploaded_at_ns: None,
            remote_etag: None,
            extra: Default::default(),
        };
        assert!(c.name_is_canonical());
    }
}
